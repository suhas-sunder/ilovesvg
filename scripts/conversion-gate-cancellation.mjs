import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
const source = await readFile(new URL('../app/utils/conversionGate.server.ts', import.meta.url), 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ES2022, target: ts.ScriptTarget.ES2022 } }).outputText;
const { getConversionGate } = await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
const gate = await getConversionGate({ maxRunning: 1, maxQueued: 2 });
const active = await gate.acquireOrQueue();
const controller = new AbortController();
const queued = gate.acquireOrQueue(null, controller.signal);
const canceled = assert.rejects(queued, { name: 'AbortError' });
assert.equal(gate.queued, 1);
controller.abort();
await Promise.race([canceled, new Promise((_, reject) => setTimeout(() => reject(new Error('Canceled queued job did not settle')), 100))]);
assert.equal(gate.queued, 0, 'canceled job must release queued closure immediately');
assert.equal(gate.running, 1, 'canceling a waiter cannot release active native work');
const alreadyAborted = new AbortController(); alreadyAborted.abort();
await assert.rejects(gate.acquireOrQueue(null, alreadyAborted.signal), { name: 'AbortError' });
assert.equal(gate.queued, 0);
const next = gate.acquireOrQueue();
active(); active();
const release = await next;
assert.equal(gate.running, 1);
assert.equal(gate.queued, 0);
release(); release();
assert.equal(gate.running, 0, 'release remains idempotent');
const activeAbort = new AbortController();
const held = await gate.acquireOrQueue(null, activeAbort.signal);
const first = gate.acquireOrQueue();
const middleAbort = new AbortController();
const middle = gate.acquireOrQueue(null, middleAbort.signal);
const rejectedMiddle = assert.rejects(middle, { name: 'AbortError' });
middleAbort.abort();
await rejectedMiddle;
const last = gate.acquireOrQueue();
activeAbort.abort();
assert.equal(gate.running, 1, 'aborting acquired work cannot release its native slot');
assert.equal(gate.queued, 2);
held();
const releaseFirst = await first;
assert.equal(gate.queued, 1, 'canceling the middle waiter preserves the first survivor');
releaseFirst();
const releaseLast = await last;
assert.equal(gate.queued, 0);
releaseLast();
assert.equal(gate.running, 0);
console.log('Conversion gate cancellation passed: queued and pre-aborted jobs, active ownership, FIFO recovery, idempotent release.');
