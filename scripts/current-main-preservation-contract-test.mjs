import assert from 'node:assert/strict';
import fs from 'node:fs';
import { assertCurrentMainPreserved, assertRouteAndNavigationContracts, routeManifestContract, CURRENT_MAIN_SHA } from './current-main-preservation-contract.mjs';
const manifest = fs.readFileSync('app/data/routeManifest.ts','utf8');
const navigation = fs.readFileSync('app/client/components/navigation/OtherToolsLinks.tsx','utf8');
const result = assertRouteAndNavigationContracts(manifest,navigation);
assert.ok(result.routes > 100 && result.navigationLinks > 100);
assert.deepEqual(assertCurrentMainPreserved('app/data/routeManifest.ts'),result);
assert.deepEqual(assertCurrentMainPreserved('app/client/components/navigation/OtherToolsLinks.tsx'),result);
const entries = routeManifestContract(manifest);
const source = entries => `export const ROUTE_MANIFEST = ${JSON.stringify(entries)} as const;`;
assert.throws(()=>assertRouteAndNavigationContracts(source([...entries,entries[0]]),navigation), /unique paths/);
assert.throws(()=>assertRouteAndNavigationContracts(source(entries.map((entry,index)=>index===0?{...entry,canonicalPath:'/nonexistent'}:entry)),navigation), /canonical target/);
assert.throws(()=>assertRouteAndNavigationContracts(manifest, navigation+'\nconst broken = {to:"/missing-public-tool"};'), /unregistered/);
const redirect = entries.find(entry=>entry.redirectTo);
assert.ok(redirect);
assert.throws(()=>assertRouteAndNavigationContracts(source(entries.map(entry=>entry===redirect?{...entry,indexable:true}:entry)),navigation), /canonical|indexable/);
assert.throws(()=>assertRouteAndNavigationContracts(source(entries.map(entry=>entry===redirect?{...entry,redirectTo:redirect.path}:entry)),navigation), /directly/);
console.log(JSON.stringify({ok:true,currentMain:CURRENT_MAIN_SHA,...result,adversarialCases:5}));
